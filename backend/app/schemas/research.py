"""
ResearchMind AI – Research Pydantic Schemas
===========================================
Input and output models for the research API and all research-related agents.

These schemas serve as the contract between:
  - The frontend and the API (request/response bodies)
  - The API and the agent layer (structured LLM output)
  - Agents and LangGraph state (shared state objects)
"""

from __future__ import annotations

from datetime import datetime
from enum import Enum
from typing import Any
from uuid import UUID, uuid4

from pydantic import BaseModel, Field, field_validator, model_validator


# ─── Enums ────────────────────────────────────────────────────────────────────


class ResearchDepth(str, Enum):
    """
    Controls how thorough the research should be.
    Affects the number of research questions and search results per question.
    """

    QUICK = "quick"            # 3–5 questions, 3 results/query
    STANDARD = "standard"      # 5–7 questions, 5 results/query
    COMPREHENSIVE = "comprehensive"  # 8–10 questions, 8 results/query


class ResearchMode(str, Enum):
    """Controls where the Researcher Agent looks for information."""

    WEB = "web"                    # Tavily web search only
    DOCUMENTS = "documents"        # Uploaded documents (RAG) only
    HYBRID = "hybrid"              # Both web and documents


class ResearchStatus(str, Enum):
    """Lifecycle states of a research job."""

    PENDING = "pending"
    PLANNING = "planning"
    AWAITING_APPROVAL = "awaiting_approval"
    RESEARCHING = "researching"
    ANALYZING = "analyzing"
    FACT_CHECKING = "fact_checking"
    WRITING_REPORT = "writing_report"
    COMPLETED = "completed"
    FAILED = "failed"
    CANCELLED = "cancelled"


class VerificationStatus(str, Enum):
    """
    Result of the Fact Checker Agent's assessment for a single claim.

    Note: VERIFIED means the claim is supported by available collected evidence.
    It does NOT guarantee the claim is universally true.
    """

    VERIFIED = "VERIFIED"
    PARTIALLY_SUPPORTED = "PARTIALLY_SUPPORTED"
    UNSUPPORTED = "UNSUPPORTED"
    CONTRADICTED = "CONTRADICTED"
    NEEDS_MORE_EVIDENCE = "NEEDS_MORE_EVIDENCE"


# ─── Research Request (API Input) ─────────────────────────────────────────────


class ResearchRequest(BaseModel):
    """
    The user's research request submitted to the API.

    This is the starting point of the entire research workflow.
    """

    topic: str = Field(
        ...,
        min_length=10,
        max_length=2000,
        description="The research topic or question. Be specific for better results.",
        examples=[
            "Analyze the future of Generative AI engineering jobs in India over the next five years."
        ],
    )
    depth: ResearchDepth = Field(
        default=ResearchDepth.STANDARD,
        description="How thorough the research should be.",
    )
    mode: ResearchMode = Field(
        default=ResearchMode.WEB,
        description="Where to search: web, uploaded documents, or both.",
    )
    max_questions: int | None = Field(
        default=None,
        ge=3,
        le=10,
        description="Override the number of research questions. None = depth default.",
    )
    max_results_per_query: int | None = Field(
        default=None,
        ge=1,
        le=15,
        description="Override max search results per query. None = depth default.",
    )
    language: str = Field(
        default="English",
        max_length=50,
        description="Language for the final report.",
    )
    document_ids: list[str] = Field(
        default_factory=list,
        description="IDs of previously uploaded documents to include in document/hybrid mode.",
    )

    @field_validator("topic")
    @classmethod
    def strip_topic(cls, v: str) -> str:
        """Remove leading/trailing whitespace from topic."""
        return v.strip()

    @model_validator(mode="after")
    def validate_document_mode(self) -> "ResearchRequest":
        """Warn if document IDs are provided but mode is WEB-only."""
        if self.document_ids and self.mode == ResearchMode.WEB:
            # Automatically upgrade to hybrid if documents are provided
            self.mode = ResearchMode.HYBRID
        return self


# ─── Research Plan (Planner Agent Output) ─────────────────────────────────────


class ResearchQuestion(BaseModel):
    """
    A single research question generated by the Planner Agent.

    Each question targets a specific aspect of the overall research topic.
    """

    id: str = Field(
        default_factory=lambda: str(uuid4()),
        description="Unique identifier for this research question.",
    )
    question: str = Field(
        ...,
        description="The research question to be answered.",
        examples=["What are the most in-demand GenAI engineering skills in India in 2024-2025?"],
    )
    category: str = Field(
        ...,
        description="Category this question belongs to (e.g., 'Skills', 'Salary', 'Risks').",
    )
    priority: int = Field(
        default=1,
        ge=1,
        le=3,
        description="Priority: 1=high, 2=medium, 3=low.",
    )
    search_queries: list[str] = Field(
        ...,
        min_length=1,
        max_length=5,
        description="Optimized search queries to answer this question.",
    )
    rationale: str = Field(
        ...,
        description="Why this question is important for the research topic.",
    )


class ResearchPlan(BaseModel):
    """
    The structured research plan produced by the Planner Agent.

    This plan is presented to the user for review before research begins.
    """

    plan_id: str = Field(
        default_factory=lambda: str(uuid4()),
        description="Unique identifier for this research plan.",
    )
    topic: str = Field(..., description="The original research topic.")
    scope_and_objectives: str = Field(
        ...,
        description="A clear statement of what this research aims to discover.",
    )
    information_categories: list[str] = Field(
        ...,
        description="High-level categories of information to gather (e.g., 'Market trends', 'Salary data').",
    )
    research_questions: list[ResearchQuestion] = Field(
        ...,
        min_length=3,
        max_length=10,
        description="The list of specific research questions to investigate.",
    )
    estimated_duration_minutes: int = Field(
        ...,
        ge=1,
        description="Estimated time to complete research (for UX display).",
    )
    depth: ResearchDepth
    mode: ResearchMode
    language: str
    created_at: datetime = Field(default_factory=datetime.utcnow)
    metadata: dict[str, Any] = Field(
        default_factory=dict,
        description="Extra planning metadata (token count, model used, etc.).",
    )


# ─── Research Source (Researcher Agent Output) ────────────────────────────────


class ResearchSource(BaseModel):
    """
    A single source collected by the Researcher Agent.

    Sources are always from real searches — never invented.
    """

    source_id: str = Field(default_factory=lambda: str(uuid4()))
    question_id: str = Field(..., description="The research question this source helps answer.")
    title: str
    url: str
    domain: str = Field(default="", description="Domain extracted from URL.")
    excerpt: str = Field(default="", description="Relevant text excerpt from the page.")
    published_date: str | None = Field(default=None, description="Publication date if available.")
    retrieved_at: datetime = Field(default_factory=datetime.utcnow)
    relevance_score: float | None = Field(default=None, ge=0.0, le=1.0)
    is_duplicate: bool = False

    @field_validator("domain", mode="before")
    @classmethod
    def extract_domain(cls, v: str, info: Any) -> str:
        """Auto-extract domain from URL if not provided."""
        if v:
            return v
        try:
            from urllib.parse import urlparse
            url = info.data.get("url", "")
            return urlparse(url).netloc
        except Exception:
            return ""


# ─── Research Findings (Analyst Agent Output) ─────────────────────────────────


class ResearchFinding(BaseModel):
    """A single finding identified by the Analyst Agent."""

    finding_id: str = Field(default_factory=lambda: str(uuid4()))
    category: str = Field(..., description="Category this finding belongs to.")
    finding: str = Field(..., description="The finding statement.")
    evidence_source_ids: list[str] = Field(
        ...,
        description="IDs of sources that support this finding.",
    )
    confidence: float = Field(ge=0.0, le=1.0, description="Analyst's confidence 0–1.")
    is_trend: bool = False
    is_opportunity: bool = False
    is_risk: bool = False
    is_contradiction: bool = False


class ResearchAnalysis(BaseModel):
    """Complete analysis produced by the Analyst Agent."""

    analysis_id: str = Field(default_factory=lambda: str(uuid4()))
    summary: str = Field(..., description="High-level summary of all findings.")
    themes: list[str] = Field(..., description="Common themes found across sources.")
    findings: list[ResearchFinding]
    contradictions: list[str] = Field(
        default_factory=list,
        description="Conflicting statements found across sources.",
    )
    evidence_gaps: list[str] = Field(
        default_factory=list,
        description="Areas where evidence was insufficient or missing.",
    )
    created_at: datetime = Field(default_factory=datetime.utcnow)


# ─── Verified Claims (Fact Checker Agent Output) ──────────────────────────────


class VerifiedClaim(BaseModel):
    """A single claim assessed by the Fact Checker Agent."""

    claim_id: str = Field(default_factory=lambda: str(uuid4()))
    claim: str = Field(..., description="The exact claim text being assessed.")
    status: VerificationStatus
    reasoning: str = Field(..., description="Explanation of why this status was assigned.")
    supporting_source_ids: list[str] = Field(
        default_factory=list,
        description="Source IDs that support the claim.",
    )
    contradicting_source_ids: list[str] = Field(
        default_factory=list,
        description="Source IDs that contradict the claim.",
    )
    note: str = Field(
        default="",
        description="Additional context (e.g., 'This claim needs recent data from 2024+').",
    )


# ─── Research Report (Report Writer Agent Output) ─────────────────────────────


class ResearchReport(BaseModel):
    """The final research report produced by the Report Writer Agent."""

    report_id: str = Field(default_factory=lambda: str(uuid4()))
    research_id: str
    title: str
    executive_summary: str
    objectives: str
    methodology: str
    key_findings: list[str]
    detailed_analysis: str
    industry_trends: list[str]
    opportunities: list[str]
    risks_and_challenges: list[str]
    verified_claims: list[VerifiedClaim]
    uncertain_findings: list[str] = Field(
        default_factory=list,
        description="Findings that lacked sufficient evidence – clearly flagged.",
    )
    limitations: str
    conclusion: str
    references: list[ResearchSource]
    created_at: datetime = Field(default_factory=datetime.utcnow)
    word_count: int = 0
    language: str = "English"


# ─── Research Job (Full Workflow State) ───────────────────────────────────────


class ResearchJobSummary(BaseModel):
    """Summary of a research job for listing in history."""

    research_id: str
    topic: str
    status: ResearchStatus
    depth: ResearchDepth
    mode: ResearchMode
    created_at: datetime
    completed_at: datetime | None = None
    source_count: int = 0
    has_report: bool = False


# ─── API Response Schemas ─────────────────────────────────────────────────────


class PlanResponse(BaseModel):
    """Response returned by the POST /api/research/plan endpoint."""

    research_id: str
    plan: ResearchPlan
    message: str = "Research plan created. Please review and approve to begin research."
